/**
 * Generates rd's key tables from Chromium's `ui/events/keycodes/dom/dom_code_data.inc`
 * (vendored next to this script, BSD-3-Clause, see THIRD_PARTY_NOTICES.md):
 *
 *   crates/rd-proto/src/keymap_gen.rs  HID usage -> DOM code, macOS kVK, Windows scancode
 *   viewer/src/input/keymap.gen.ts     DOM `KeyboardEvent.code` -> HID usage
 *
 * Usage: bun tools/gen-keymap/gen.ts [--check]
 *   --check  only verify that both outputs are up to date (exit 1 if not).
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";

const HERE = import.meta.dir;
const ROOT = join(HERE, "..", "..");
const SOURCE = join(HERE, "dom_code_data.inc");
const RUST_OUT = join(ROOT, "crates/rd-proto/src/keymap_gen.rs");
const TS_OUT = join(ROOT, "viewer/src/input/keymap.gen.ts");

/**
 * HID usage pages that are exported: Generic Desktop (Sleep, WakeUp, Fn), Keyboard/Keypad
 * and Consumer (media/browser keys). Chromium's page-0 rows are non-USB pseudo codes.
 */
const PAGES = new Set([0x01, 0x07, 0x0c]);

/**
 * Additions to Chromium's Mac column. Chromium leaves Fn unmapped (its own TODO lists
 * "Mac#003f kVK_Function"); the macOS agent injects it as a modifier.
 */
const MAC_OVERRIDES = new Map<number, number>([[0x010097, 0x3f]]);

/** Chromium's "no key" markers. */
const MAC_NONE = 0xffff;
const WIN_NONE = 0x0000;

interface Key {
  hid: number;
  code: string;
  mac: number | null;
  win: number | null;
}

const HEADER = [
  "@generated by tools/gen-keymap/gen.ts from Chromium's ui/events/keycodes/dom/dom_code_data.inc",
  "(BSD-3-Clause, see THIRD_PARTY_NOTICES.md). DO NOT EDIT; run `bun tools/gen-keymap/gen.ts`.",
];

function parse(text: string): Key[] {
  // Drop comments first: they contain commented-out DOM_CODE rows.
  const src = text.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
  const num = "\\s*(0x[0-9a-fA-F]+)\\s*";
  const row = new RegExp(
    `\\bDOM_CODE\\(${num},${num},${num},${num},${num},\\s*(NULL|"[^"]*")\\s*,\\s*(\\w+)\\s*\\)`,
    "g",
  );
  const rows = [...src.matchAll(row)];
  const declared = src.match(/\bDOM_CODE\(/g)?.length ?? 0;
  if (rows.length === 0 || rows.length !== declared) {
    throw new Error(`parsed ${rows.length} of ${declared} DOM_CODE rows; did the format change?`);
  }

  type Row = [usb: string, evdev: string, xkb: string, win: string, mac: string, code: string];
  const keys: Key[] = [];
  for (const match of rows) {
    // All seven groups are mandatory, so a match always has every field.
    const [usb, , , win, mac, code] = match.slice(1) as Row;
    if (code === "NULL" || code === '""') continue;
    const hid = Number.parseInt(usb, 16);
    if (!PAGES.has(hid >>> 16)) continue;
    const macCode = Number.parseInt(mac, 16);
    const winCode = Number.parseInt(win, 16);
    keys.push({
      hid,
      code: code.slice(1, -1),
      mac: macCode === MAC_NONE ? null : macCode,
      win: winCode === WIN_NONE ? null : winCode,
    });
  }

  for (const [hid, mac] of MAC_OVERRIDES) {
    const key = keys.find((k) => k.hid === hid);
    if (!key) throw new Error(`mac override for missing HID ${hexHid(hid)}`);
    if (key.mac !== null) {
      throw new Error(`Chromium now maps ${key.code} to mac ${key.mac}; drop the override`);
    }
    key.mac = mac;
  }

  keys.sort((a, b) => a.hid - b.hid);
  assertUnique(keys, "hid", (k) => k.hid);
  assertUnique(keys, "code", (k) => k.code);
  return keys;
}

function assertUnique<T>(keys: Key[], what: string, field: (k: Key) => T): void {
  const seen = new Set<T>();
  for (const k of keys) {
    const v = field(k);
    if (seen.has(v)) throw new Error(`duplicate ${what}: ${String(v)} (${k.code})`);
    seen.add(v);
  }
}

const hex = (n: number, digits: number): string => `0x${n.toString(16).padStart(digits, "0")}`;
/** `0x0007_0004`: page and usage separated for readability. */
const hexHid = (hid: number): string =>
  `${hex(hid >>> 16, 4)}_${(hid & 0xffff).toString(16).padStart(4, "0")}`;

function rust(keys: Key[]): string {
  const opt = (v: number | null, digits: number) =>
    v === null ? "None" : `Some(${hex(v, digits)})`;
  // Align the columns: one key per line reads like the table it is.
  const codeWidth = Math.max(...keys.map((k) => k.code.length)) + 3; // quotes + comma
  const macWidth = "Some(0x00),".length;
  const rows = keys.map((k) => {
    const code = `"${k.code}",`.padEnd(codeWidth);
    const mac = `${opt(k.mac, 2)},`.padEnd(macWidth);
    const win = opt(k.win, 4);
    return `    KeyEntry { hid: ${hexHid(k.hid)}, code: ${code} mac: ${mac} win: ${win} },`;
  });
  return [
    ...HEADER.map((l) => `// ${l}`),
    "",
    "use super::KeyEntry;",
    "",
    "/// Every key that has a DOM `code`, sorted by HID usage.",
    "#[rustfmt::skip]",
    "pub static KEYS: &[KeyEntry] = &[",
    ...rows,
    "];",
    "",
  ].join("\n");
}

function typescript(keys: Key[]): string {
  return [
    ...HEADER.map((l) => `// ${l}`),
    "",
    "/** `KeyboardEvent.code` -> USB HID usage (`(page << 16) | usage`) sent in KEY messages. */",
    "export const CODE_TO_HID: Readonly<Record<string, number>> = {",
    ...keys.map((k) => `  ${k.code}: ${hex(k.hid, 8)},`),
    "};",
    "",
    "const hasOwn = Object.prototype.hasOwnProperty;",
    "",
    "/** HID usage for a `KeyboardEvent.code`; `undefined` if the protocol has no such key. */",
    "export function hidForCode(code: string): number | undefined {",
    "  return hasOwn.call(CODE_TO_HID, code) ? CODE_TO_HID[code] : undefined;",
    "}",
    "",
  ].join("\n");
}

function readOrEmpty(path: string): string {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return "";
  }
}

function main(): void {
  const check = process.argv.includes("--check");
  const keys = parse(readFileSync(SOURCE, "utf8"));
  const outputs: [string, string][] = [
    [RUST_OUT, rust(keys)],
    [TS_OUT, typescript(keys)],
  ];

  let stale = 0;
  for (const [path, content] of outputs) {
    const name = relative(ROOT, path);
    if (readOrEmpty(path) === content) {
      console.log(`up to date: ${name}`);
    } else if (check) {
      console.error(`STALE: ${name}`);
      stale++;
    } else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
      console.log(`wrote: ${name}`);
    }
  }
  const mac = keys.filter((k) => k.mac !== null).length;
  const win = keys.filter((k) => k.win !== null).length;
  console.log(`${keys.length} keys (${mac} with a macOS keycode, ${win} with a Windows scancode)`);
  if (stale > 0) {
    console.error("run `bun tools/gen-keymap/gen.ts` to regenerate");
    process.exit(1);
  }
}

main();
